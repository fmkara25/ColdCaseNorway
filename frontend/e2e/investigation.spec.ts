import { expect, test } from "@playwright/test";

test("case branches progress through reviewed evidence, saved links and verified claims without leaking to another browser", async ({ page, browser }) => {
  const base = "/api/cases/1999-1218";
  const session = base + "/investigation";
  const headers = { "X-ColdCase-Request": "1" };
  const post = async (path: string, data: unknown = {}) => {
    const response = await page.request.post(session + path, { headers, data });
    expect(response.ok(), await response.text()).toBeTruthy();
    return response.json();
  };
  const review = async (...ids: string[]) => { for (const id of ids) await post(`/evidence/${id}/review`); };
  const action = (id: string, locationIds: string[] | null = null) => post(`/actions/${id}`, { locationIds });
  const connect = async (fromId: string, toId: string) => {
    const response = await page.request.get(session);
    const snapshot = await response.json();
    for (const id of [fromId, toId]) if (!snapshot.board.positions.some((p: { id: string }) => p.id === id))
      snapshot.board.positions.push({ id, x: 40 + snapshot.board.positions.length * 30, y: 80 });
    snapshot.board.connections.push({ id: crypto.randomUUID(), fromId, toId, label: "Undersøk sammenhengen" });
    const saved = await page.request.put(session + "/board", { headers, data: snapshot });
    expect(saved.ok(), await saved.text()).toBeTruthy();
  };
  await post("");
  const locked = await page.request.post(session + "/actions/lars-events", { headers, data: {} });
  expect(locked.status()).toBe(404);
  await review("hotel-log", "maria-statement", "phone-log", "jonas-statement", "bus-ticket", "market-witness");
  await action("find-note"); await action("phone-lookup");
  await review("ingrid-note", "phone-match");
  await connect("person:maria", "evidence:ingrid-note");
  await page.goto("/cases/1999-1218/people/maria");
  await page.getByRole("button", { name: "Spør om notatet og den avtalte bagen" }).click();
  await expect(page.locator(".action-history")).toContainText("Bagen ble stående igjen");
  await connect("evidence:phone-match", "evidence:jonas-statement");
  await action("jonas-call");
  await review("travel-bag");
  await connect("evidence:travel-bag", "evidence:bus-ticket");
  await action("witness-followup");
  await review("vehicle-witness", "erik-phone");
  const wrongRoute = await page.request.post(session + "/actions/erik-route", { headers, data: { locationIds: ["hotel", "market"] } });
  expect(wrongRoute.status()).toBe(400);
  await action("erik-route", ["market", "payphone"]);
  await action("company-records");
  const people = await (await page.request.get(base + "/people")).json();
  expect(people.some((p: { id: string }) => p.id === "lars")).toBeTruthy();
  const openingMap = await (await page.request.get(base + "/map")).json();
  expect(openingMap.locations.some((p: { id: string }) => p.id === "mill-road")).toBeFalsy();
  const other = await browser.newContext();
  const privatePeople = await (await other.request.get("http://127.0.0.1:5173" + base + "/people")).json();
  expect(privatePeople.some((p: { id: string }) => p.id === "lars")).toBeFalsy();
  await other.close();
  await review("vehicle-log", "work-order", "lars-statement");
  await connect("evidence:vehicle-log", "evidence:work-order");
  await action("mileage"); await review("card-transaction"); await action("terminal");
  await action("lars-early");
  await connect("person:lars", "evidence:vehicle-log");
  await action("lars-mileage"); await review("emergency-claim"); await action("check-emergency");
  await review("station-receipt"); await connect("person:lars", "evidence:station-receipt");
  await action("lars-receipt"); await review("bumper-report", "clean-vehicle");
  await connect("evidence:bumper-report", "evidence:clean-vehicle");
  await action("lars-damage"); await review("lars-slip");
  const completed = await action("lars-events");
  const repeated = await action("lars-events");
  expect(repeated.version).toBe(completed.version);
  const materials = await (await page.request.get(base + "/evidence")).json();
  expect(materials.some((e: { id: string }) => e.id === "lars-account")).toBeTruthy();
  const fullRoute = await page.request.post(base + "/map/estimate", { data: { locationIds: ["depot", "work-site", "market", "mill-road", "hospital-turn", "mill-road", "service-area", "station", "depot"] } });
  expect(fullRoute.ok()).toBeTruthy();
  expect((await fullRoute.json()).meters).toBe(43200);
  await page.goto("/cases/1999-1218/people/lars");
  await expect(page.locator(".action-history")).toContainText("Jeg skulle ha ringt etter hjelp");
  await page.reload();
  await expect(page.locator(".action-history")).toContainText("Jeg skulle ha ringt etter hjelp");
  await review("ingrid-letter", "lars-account", "no-extra-job");
  const finalView = await page.request.get(session + "/reconstruction");
  expect(finalView.ok()).toBeTruthy();
  const finalText = await finalView.text();
  expect(finalText).not.toContain("expectedAnswers");
  expect(finalText).not.toContain("requiredWaypoints");
  expect(finalText).not.toContain("epilogue");
  const evidenceIds = ["vehicle-witness", "vehicle-log", "work-order", "station-receipt", "bumper-report", "clean-vehicle", "bus-ticket"];
  const routeIds = ["depot", "work-site", "market", "mill-road", "hospital-turn", "mill-road", "service-area", "station", "depot"];
  const answers = { driver: "lars", entry: "voluntary", event: "accident", concealment: "fear", location: "mill-road" };
  const wrong = await page.request.post(session + "/reconstruction", { headers, data: { answers: { ...answers, driver: "erik" }, evidenceIds, routeIds } });
  expect((await wrong.json()).accepted).toBeFalsy();
  const notClosed = await (await page.request.get(session + "/progress")).json();
  expect(notClosed.isReconstructed).toBeFalsy();
  await page.goto("/cases/1999-1218/map");
  const names = ["Selskapets base", "Arbeidsstedet", "Butikken", "Gamle Møllevei", "Veikrysset mot sykehuset", "Gamle Møllevei", "Det gamle serviceområdet", "Skardal Nord bensinstasjon", "Selskapets base"];
  for (const name of names) await page.getByRole("button", { name, exact: true }).click();
  await expect(page.locator(".route-result")).toContainText("43,2 km");
  await page.getByRole("link", { name: "Bruk ruten i rekonstruksjonen" }).click();
  await page.getByLabel("Hvem kjørte bilen?", { exact: true }).selectOption("lars");
  await page.getByLabel("Hvordan kom Ingrid inn i bilen?", { exact: true }).selectOption("voluntary");
  await page.getByLabel("Hva utløste hendelsen?", { exact: true }).selectOption("accident");
  await page.getByLabel("Hvorfor ble hendelsen skjult?", { exact: true }).selectOption("fear");
  await page.getByLabel("Hvor oppsto den sentrale hendelsen?", { exact: true }).selectOption("mill-road");
  for (const title of ["Kjøretøyet ved butikken", "Kjørebok: bil 14", "Arbeidsordren", "Varelinjene fra Skardal Nord", "Skaden foran til høyre", "Den rengjorte bilen", "Bussbillett til Trondheim"]) await page.getByLabel(`Velg ${title}`, { exact: true }).check();
  await page.getByRole("button", { name: "Lever rekonstruksjonen" }).click();
  await expect(page.getByRole("heading", { name: "Rekonstruksjon levert" })).toBeVisible();
  await expect(page.locator(".epilogue")).toContainText("Ingrid ble ikke funnet");
  await page.reload();
  await expect(page.getByRole("heading", { name: "Rekonstruksjon levert" })).toBeVisible();
  await expect(page.locator(".workspace-header .status")).toHaveText("Rekonstruert");
  const completedAgain = await page.request.post(session + "/reconstruction", { headers, data: { answers, evidenceIds, routeIds } });
  expect((await completedAgain.json()).accepted).toBeTruthy();
  const fresh = await browser.newContext();
  const privateEnding = await fresh.request.get("http://127.0.0.1:5173" + session + "/reconstruction");
  expect(privateEnding.status()).toBe(404);
  await fresh.close();
});
